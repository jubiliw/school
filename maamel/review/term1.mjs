// The prompts are new applications of the original question objectives.
function section(id,title,page,rows,practical){
  const questions=rows.map(([source,prompt,answer,...distractors],i)=>{
    const options=distractors.slice();
    const correct=(i+page)% (options.length+1);
    options.splice(correct,0,answer);
    return {page:source,prompt,options,correct};
  });
  return {id,title,page,questions,...(practical?{practical}: {})};
}
